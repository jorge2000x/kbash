@pytest.mark.parametrize("nome", sorted(ESPERADO))
def test_build_option_caracterizacao(nome: str) -> None:
    corpo = CASOS[nome]
    try:
        resultado = parse_text(CAB + corpo + "\n" + FIM, Path("p.sh"))
    except (ParseError, ValidationError) as erro:
        obtido = ("erro", erro.diagnostic.message, erro.diagnostic.line)
    else:
        avisos = [(w.message, w.line) for w in resultado.warnings]
        opcoes = [dataclasses.asdict(o) for o in resultado.script.options]
        obtido = ("ok", avisos, opcoes)
    assert obtido == ESPERADO[nome]
